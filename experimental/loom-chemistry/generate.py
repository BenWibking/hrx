def body(name):
    match = re.search(r"\b" + re.escape(name) + r"\s*\([^;{]*\)\s*\{", SOURCE)
    if not match:
        raise ValueError(name)
    start = match.end()
    depth = 1
    end = start
    while depth:
        depth += (SOURCE[end] == "{") - (SOURCE[end] == "}")
        end += 1
    return SOURCE[start:end - 1]


def replace(text, old, new, count=1):
    assert text.count(old) == count, (old, text.count(old), count)
    return text.replace(old, new)


def common(text):
    text = text.replace("integrators::", "").replace("pc::", "")
    text = text.replace("std::size_t", "size_type").replace("std::uint64_t", "u64")
    text = text.replace("std::", "math::")
    text = re.sub(r"IntegratorResult::(\w+)", r"\1", text)
    # The source chemistry expressions use literal, one-based output indices.
    text = re.sub(r'\bX\((\d+)\)', lambda m: f'xn[{int(m[1])}]', text)
    text = re.sub(r'\bydot\((\d+)\)', lambda m: f'out[{int(m[1]) - 1}]', text)
    text = re.sub(r'\bjac\((\d+),(\d+)\)',
                  lambda m: f'out[{int(m[1]) - 1}][{int(m[2]) - 1}]', text)
    return text


