def shallow_conditionals(name, text):
    """Outline parenthesized ternaries, retaining lazy branch evaluation.

    All captured xN/T/z variables in these three generated routines are Real
    locals with no mutation during an expression. xn is a read-only pointer.
    auto return deduction preserves bool/int/Real conditional-expression types.
    Each helper contains just one ternary; no eager select or reassociation.
    """
    ordinal = 0
    while '?' in text:
        stack = []
        conditional_parents = set()
        found = None
        for pos, char in enumerate(text):
            if char == '(':
                stack.append(pos)
            elif char == '?':
                conditional_parents.add(stack[-1])
            elif char == ')':
                start = stack.pop()
                if start in conditional_parents:
                    found = start, pos + 1
                    break
        assert found, name
        start, end = found
        expression = text[start:end]
        assert expression.count('?') == 1
        captures = sorted(set(re.findall(r'\b(?:x\d+|T|z|xn)\b', expression)))
        if 'X(' in expression and 'xn' not in captures:
            captures.append('xn')
        helper = f'{name}_choice_{ordinal}'
        parameters = ', '.join(('const Real* ' if v == 'xn' else 'Real ') + v for v in captures)
        emit('auto ' + helper + '(' + parameters + ')', 'return ' + expression + ';')
        text = text[:start] + helper + '(' + ', '.join(captures) + ')' + text[end:]
        ordinal += 1
    return text


for name, signature in [('rhs_specie', 'void rhs_specie(Real temperature, Real* out, const Real* xn, Real z)'),
                         ('rhs_eint', 'Real rhs_eint(Real temperature, const Real* xn, Real z)'),
                         ('jac_nuc', 'void jac_nuc(Real temperature, Real (*out)[15], const Real* xn, Real z)')]:
    emit(signature, shallow_conditionals(name, body(name).replace('state.T', 'temperature')))
